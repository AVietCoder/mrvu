-- ---------------------------------------------------------------- Câu hỏi AI
CREATE TABLE IF NOT EXISTS public.seo_aiq_projects(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT, domain TEXT, brands_json TEXT,
  competitors_json TEXT, topics_json TEXT, location INTEGER DEFAULT 2704, language TEXT DEFAULT 'vi',
  platforms_json TEXT, auto_check INTEGER DEFAULT 0, auto_days INTEGER DEFAULT 30, auto_top INTEGER DEFAULT 30,
  site_id BIGINT, tech_json TEXT, plan_json TEXT, insights_json TEXT, created_at TEXT);
CREATE TABLE IF NOT EXISTS public.seo_aiq_questions(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT, question TEXT, norm TEXT,
  cluster TEXT, intent TEXT, sources_json TEXT, ai_volume INTEGER, gsc_impr INTEGER, gsc_pos DOUBLE PRECISION, priority INTEGER DEFAULT 2,
  status TEXT DEFAULT 'new', target_url TEXT, note TEXT, created_at TEXT, UNIQUE(project_id, norm));
CREATE TABLE IF NOT EXISTS public.seo_aiq_runs(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT, at TEXT, platforms_json TEXT,
  n_questions INTEGER, summary_json TEXT, cost_usd DOUBLE PRECISION, auto INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS public.seo_aiq_checks(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id BIGINT, project_id BIGINT, question_id BIGINT,
  platform TEXT, at TEXT, ok INTEGER, answer TEXT, mentioned INTEGER, cited INTEGER, mention_pos DOUBLE PRECISION,
  sources_json TEXT, brands_json TEXT, competitors_json TEXT, note TEXT);
CREATE INDEX IF NOT EXISTS ix_seo_aiq_checks ON public.seo_aiq_checks(question_id, platform, id);
CREATE INDEX IF NOT EXISTS ix_seo_aiq_checks_run ON public.seo_aiq_checks(run_id);
CREATE INDEX IF NOT EXISTS ix_seo_aiq_checks_project ON public.seo_aiq_checks(project_id);
CREATE TABLE IF NOT EXISTS public.seo_aiq_advice(question_id BIGINT PRIMARY KEY, at TEXT, data_json TEXT);

-- ---------------------------------------------------------------- Bản đồ website
CREATE TABLE IF NOT EXISTS public.seo_smap_sites(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, domain TEXT UNIQUE, max_pages INTEGER DEFAULT 800,
  psi_mode TEXT DEFAULT 'smart', use_labs INTEGER DEFAULT 1, inspect INTEGER DEFAULT 1, auto INTEGER DEFAULT 0, auto_days INTEGER DEFAULT 30,
  site_id BIGINT, created_at TEXT);
CREATE TABLE IF NOT EXISTS public.seo_smap_pages(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id BIGINT, url TEXT, ukey TEXT, type TEXT, status INTEGER,
  final_url TEXT, active INTEGER DEFAULT 1, in_sitemap INTEGER DEFAULT 0, title TEXT, h1 TEXT, words INTEGER, noindex INTEGER DEFAULT 0,
  canonical TEXT, depth INTEGER, inlinks INTEGER DEFAULT 0, outlinks INTEGER DEFAULT 0, links_json TEXT, anchors_in_json TEXT, broken_json TEXT,
  primary_kw TEXT, secondary_json TEXT, geo_json TEXT, intent TEXT, cluster TEXT, role TEXT, kw_note TEXT, kw_locked INTEGER DEFAULT 0, kw_at TEXT,
  seo INTEGER, seo_fails_json TEXT, geo_score INTEGER, geo_fails_json TEXT, psi_json TEXT, index_json TEXT,
  gsc_json TEXT, ga_json TEXT, ranks_json TEXT, issues_json TEXT, value DOUBLE PRECISION DEFAULT 0, advice_json TEXT,
  first_seen TEXT, last_seen TEXT, UNIQUE(site_id, ukey));
CREATE TABLE IF NOT EXISTS public.seo_smap_cycles(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id BIGINT, at TEXT, auto INTEGER DEFAULT 0,
  summary_json TEXT, diff_json TEXT, cannibal_json TEXT, report_json TEXT, notes_json TEXT, cost_usd DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS public.seo_smap_snaps(
  cycle_id BIGINT, page_id BIGINT, clicks INTEGER, impr INTEGER, pos DOUBLE PRECISION, seo INTEGER, geo INTEGER,
  perf INTEGER, inlinks INTEGER, status INTEGER, primary_kw TEXT, rank INTEGER, PRIMARY KEY(cycle_id, page_id));
CREATE INDEX IF NOT EXISTS ix_seo_smap_snaps_page ON public.seo_smap_snaps(page_id);
CREATE TABLE IF NOT EXISTS public.seo_smap_links(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id BIGINT, from_id BIGINT, to_id BIGINT, anchor TEXT,
  reason TEXT, kind TEXT, priority DOUBLE PRECISION, status TEXT DEFAULT 'todo', place_json TEXT, created_at TEXT, updated_at TEXT,
  UNIQUE(site_id, from_id, to_id));
CREATE TABLE IF NOT EXISTS public.seo_smap_stage(
  job_id TEXT, n INTEGER, ukey TEXT, data_json TEXT, PRIMARY KEY(job_id, ukey));

-- ---------------------------------------------------------------- RLS: chặn hết từ trình duyệt
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['seo_aiq_projects','seo_aiq_questions','seo_aiq_runs','seo_aiq_checks','seo_aiq_advice',
    'seo_smap_sites','seo_smap_pages','seo_smap_cycles','seo_smap_snaps','seo_smap_links','seo_smap_stage']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_deny_all', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (false) WITH CHECK (false)', t || '_deny_all', t);
  END LOOP;
END $$;

