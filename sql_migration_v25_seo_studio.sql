-- ---------------------------------------------------------------- Volume
CREATE TABLE IF NOT EXISTS public.seo_sessions(
  id TEXT PRIMARY KEY, created_at TEXT, location TEXT, language TEXT,
  count INTEGER, total_volume INTEGER, cost DOUBLE PRECISION, rows_json TEXT);

-- ---------------------------------------------------------------- Rank Tracker
CREATE TABLE IF NOT EXISTS public.seo_tracked(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, domain TEXT, keyword TEXT,
  location TEXT, language TEXT, created_at TEXT,
  UNIQUE(domain, keyword, location));
CREATE TABLE IF NOT EXISTS public.seo_ranks(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tracked_id BIGINT, engine TEXT,
  checked_at TEXT, position INTEGER, url TEXT, depth INTEGER, cost DOUBLE PRECISION);
CREATE INDEX IF NOT EXISTS ix_seo_ranks ON public.seo_ranks(tracked_id, engine, checked_at);

-- ---------------------------------------------------------------- Audit
CREATE TABLE IF NOT EXISTS public.seo_audit_sites(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, domain TEXT UNIQUE, start_url TEXT,
  crawled_at TEXT, method TEXT, count INTEGER);
CREATE TABLE IF NOT EXISTS public.seo_audit_pages(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id BIGINT, url TEXT, type TEXT, source TEXT,
  UNIQUE(site_id, url));
CREATE TABLE IF NOT EXISTS public.seo_audit_results(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, page_id BIGINT, audited_at TEXT, score INTEGER,
  keyword TEXT, report_json TEXT, ai_json TEXT);
CREATE INDEX IF NOT EXISTS ix_seo_ar ON public.seo_audit_results(page_id, audited_at);

-- ---------------------------------------------------------------- Đăng nhập Google
CREATE TABLE IF NOT EXISTS public.seo_auth_sessions(
  token_hash TEXT PRIMARY KEY, email TEXT, name TEXT, picture TEXT,
  created BIGINT, expires BIGINT, ua TEXT);

-- ---------------------------------------------------------------- Autopost
CREATE TABLE IF NOT EXISTS public.seo_ap_sites(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT, kind TEXT, url TEXT, username TEXT, secret TEXT,
  category_id INTEGER, category_name TEXT, post_status TEXT DEFAULT 'draft', seo_plugin TEXT DEFAULT 'none',
  image_mode TEXT DEFAULT 'none', images_per_post INTEGER DEFAULT 2, word_target INTEGER DEFAULT 1200,
  extra_prompt TEXT DEFAULT '', auto_enabled INTEGER DEFAULT 0, per_day INTEGER DEFAULT 2,
  hour_from INTEGER DEFAULT 8, hour_to INTEGER DEFAULT 21, created_at TEXT);
CREATE TABLE IF NOT EXISTS public.seo_ap_keywords(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id BIGINT, keyword TEXT, status TEXT DEFAULT 'pending',
  post_id BIGINT, error TEXT, created_at TEXT, updated_at TEXT, brief_json TEXT, UNIQUE(site_id, keyword));
-- brief_json: định hướng viết từ "Gợi ý chủ đề" (thêm 19/10/2026; bản đã chạy trước đó được bổ sung ở v26)
ALTER TABLE public.seo_ap_keywords ADD COLUMN IF NOT EXISTS brief_json TEXT;
CREATE TABLE IF NOT EXISTS public.seo_ap_posts(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id BIGINT, keyword_id BIGINT, keyword TEXT, title TEXT,
  slug TEXT, meta_title TEXT, meta_description TEXT, excerpt TEXT, tags_json TEXT, html TEXT,
  images_json TEXT, status TEXT, remote_id TEXT, remote_url TEXT, remote_status TEXT, usage_json TEXT,
  created_at TEXT, published_at TEXT);
CREATE TABLE IF NOT EXISTS public.seo_ap_logs(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT, site_id BIGINT, level TEXT, message TEXT);
-- Thư viện ảnh (thay thư mục anh-thu-vien/): file nằm trong Storage bucket seo-images
CREATE TABLE IF NOT EXISTS public.seo_ap_library(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, path TEXT NOT NULL UNIQUE,
  mime TEXT, size INTEGER, created_at TEXT);

-- Gợi ý chủ đề (topics.ts): các lần phân tích, mở lại miễn phí
CREATE TABLE IF NOT EXISTS public.seo_tp_runs(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TEXT, site_id BIGINT, seed TEXT, competitors_json TEXT,
  mode TEXT, location TEXT, result_json TEXT, cost_usd DOUBLE PRECISION);

-- ---------------------------------------------------------------- GEO
CREATE TABLE IF NOT EXISTS public.seo_geo_checks(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TEXT, url TEXT, keyword TEXT, location TEXT,
  score INTEGER, has_aio INTEGER, cited INTEGER, report_json TEXT);

-- ---------------------------------------------------------------- Backlink
CREATE TABLE IF NOT EXISTS public.seo_bl_sites(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, domain TEXT UNIQUE, competitors_json TEXT, gap_json TEXT,
  gap_at TEXT, created_at TEXT);
CREATE TABLE IF NOT EXISTS public.seo_bl_snapshots(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id BIGINT, at TEXT, source TEXT,
  summary_json TEXT, domains_json TEXT, links_json TEXT, lost_json TEXT, cost DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS public.seo_bl_opps(
  site_id BIGINT, domain TEXT, status TEXT DEFAULT 'new', note TEXT DEFAULT '',
  examples_json TEXT, draft_json TEXT, updated_at TEXT, PRIMARY KEY(site_id, domain));

-- ---------------------------------------------------------------- Search Console + GA4
CREATE TABLE IF NOT EXISTS public.seo_gsc_rows(period TEXT, query TEXT, page TEXT, clicks INTEGER, impressions INTEGER, ctr DOUBLE PRECISION, position DOUBLE PRECISION);
CREATE INDEX IF NOT EXISTS ix_seo_gsc_rows ON public.seo_gsc_rows(period, query);
CREATE TABLE IF NOT EXISTS public.seo_gsc_pages(period TEXT, page TEXT, clicks INTEGER, impressions INTEGER, ctr DOUBLE PRECISION, position DOUBLE PRECISION);
CREATE INDEX IF NOT EXISTS ix_seo_gsc_pages ON public.seo_gsc_pages(period);
CREATE TABLE IF NOT EXISTS public.seo_gsc_daily(date TEXT PRIMARY KEY, clicks INTEGER, impressions INTEGER, ctr DOUBLE PRECISION, position DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS public.seo_ga_pages(period TEXT, path TEXT, sessions INTEGER, engaged INTEGER, engagement_rate DOUBLE PRECISION, key_events DOUBLE PRECISION, avg_duration DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS public.seo_ga_daily(date TEXT PRIMARY KEY, sessions INTEGER, key_events DOUBLE PRECISION);
CREATE TABLE IF NOT EXISTS public.seo_gsc_inspect(url TEXT PRIMARY KEY, at TEXT, verdict TEXT, coverage TEXT, indexing TEXT, robots TEXT,
  "fetch" TEXT, google_canonical TEXT, user_canonical TEXT, last_crawl TEXT, mobile TEXT);
CREATE TABLE IF NOT EXISTS public.seo_gsc_ai(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT, ref TEXT, at TEXT, data_json TEXT);
CREATE TABLE IF NOT EXISTS public.seo_gsc_meta(key TEXT PRIMARY KEY, value TEXT);
-- Dữ liệu đồng bộ được ghi vào bảng tạm trước, đổi sang bản mới ở bước cuối
-- (bản Python xoá rồi ghi trong một giao dịch; ở đây việc đồng bộ chia nhiều bước).
CREATE TABLE IF NOT EXISTS public.seo_gsc_stage(sync_id TEXT, kind TEXT, period TEXT, data_json TEXT);
CREATE INDEX IF NOT EXISTS ix_seo_gsc_stage ON public.seo_gsc_stage(sync_id, kind);

-- ---------------------------------------------------------------- Chi phí
CREATE TABLE IF NOT EXISTS public.seo_spend(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT, month TEXT, module TEXT, action TEXT,
  usd DOUBLE PRECISION, detail TEXT);
CREATE INDEX IF NOT EXISTS ix_seo_spend ON public.seo_spend(month);

-- ---------------------------------------------------------------- Mới: cấu hình + tác vụ
-- Một dòng key='config' chứa JSON thay cho config.json. Khóa bí mật KHÔNG lưu ở đây
-- (đặt trong biến môi trường); riêng khóa service account Google tải lên từ giao
-- diện được lưu ĐÃ MÃ HÓA (AES-GCM bằng SEO_SECRET_KEY).
CREATE TABLE IF NOT EXISTS public.seo_config(key TEXT PRIMARY KEY, value JSONB NOT NULL DEFAULT '{}'::jsonb, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
INSERT INTO public.seo_config(key, value) VALUES ('config', '{}'::jsonb) ON CONFLICT (key) DO NOTHING;

-- Tác vụ dài (crawl, viết bài, GEO, đồng bộ…): mỗi lần trình duyệt hỏi tiến độ thì
-- server chạy MỘT bước rồi lưu trạng thái. locked_until chống hai lần hỏi chạy trùng.
CREATE TABLE IF NOT EXISTS public.seo_jobs(
  id TEXT PRIMARY KEY, kind TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'running',
  message TEXT, result JSONB, state JSONB NOT NULL DEFAULT '{}'::jsonb, extra JSONB NOT NULL DEFAULT '{}'::jsonb,
  attempts INTEGER NOT NULL DEFAULT 0, locked_until TIMESTAMPTZ, auto BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS ix_seo_jobs_status ON public.seo_jobs(status, kind);

-- ---------------------------------------------------------------- RLS: chặn hết từ trình duyệt
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['seo_sessions','seo_tracked','seo_ranks','seo_audit_sites','seo_audit_pages','seo_audit_results',
    'seo_auth_sessions','seo_ap_sites','seo_ap_keywords','seo_ap_posts','seo_ap_logs','seo_ap_library','seo_tp_runs','seo_geo_checks',
    'seo_bl_sites','seo_bl_snapshots','seo_bl_opps','seo_gsc_rows','seo_gsc_pages','seo_gsc_daily','seo_ga_pages','seo_ga_daily',
    'seo_gsc_inspect','seo_gsc_ai','seo_gsc_meta','seo_gsc_stage','seo_spend','seo_config','seo_jobs']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_deny_all', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (false) WITH CHECK (false)', t || '_deny_all', t);
  END LOOP;
END $$;

