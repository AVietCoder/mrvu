CREATE TABLE IF NOT EXISTS public.user_sessions (
  token_hash     text        PRIMARY KEY,
  user_id        text        NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  user_agent     text,
  ip             text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  last_seen_at   timestamptz NOT NULL DEFAULT now(),
  revoked_at     timestamptz,
  revoked_reason text,
  revoked_by     text
);
CREATE INDEX IF NOT EXISTS ix_user_sessions_user ON public.user_sessions(user_id);
CREATE INDEX IF NOT EXISTS ix_user_sessions_seen ON public.user_sessions(last_seen_at DESC);

-- Có IP + thiết bị của nhân viên → chặn hết từ trình duyệt; server dùng service role.
ALTER TABLE public.user_sessions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS user_sessions_deny_all ON public.user_sessions;
CREATE POLICY user_sessions_deny_all ON public.user_sessions
  FOR ALL TO anon, authenticated USING (false) WITH CHECK (false);

-- Kết quả xử lý cuối: thêm "Khách không đồng ý thay / sửa chữa".
DO $$
DECLARE c text;
BEGIN
  FOR c IN
    SELECT conname FROM pg_constraint
    WHERE conrelid = 'public.warranty_tickets'::regclass AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%final_action%'
  LOOP
    EXECUTE format('ALTER TABLE public.warranty_tickets DROP CONSTRAINT %I', c);
  END LOOP;
END $$;
ALTER TABLE public.warranty_tickets ADD CONSTRAINT warranty_tickets_final_action_check
  CHECK (final_action IS NULL OR final_action IN ('buy_part', 'free_support', 'replace_new', 'repair', 'customer_declined'));

